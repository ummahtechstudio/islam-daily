function applyHisnul() {
  const data = JSON.parse(fs.readFileSync(HISNUL_PATH, 'utf-8'));
  let updated = 0;
  let missing = [];

  for (const cat of data) {
    const urduArr = HISNUL_URDU[cat.id];
    if (!urduArr) {
      console.error(`No Urdu mapping for category: ${cat.id}`);
      process.exit(1);
    }
    if (urduArr.length !== cat.duas.length) {
      console.error(
        `Length mismatch for ${cat.id}: duas=${cat.duas.length} urdu=${urduArr.length}`,
      );
      process.exit(1);
    }
    for (let i = 0; i < cat.duas.length; i++) {
      cat.duas[i].urdu = urduArr[i];
      updated++;
    }
  }

  fs.writeFileSync(HISNUL_PATH, JSON.stringify(data, null, 2) + '\n', 'utf-8');
  console.log(`hisnul_muslim.json: ${updated} duas updated.`);
  return updated;
}

